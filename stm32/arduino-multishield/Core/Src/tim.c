void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef* htim)
{
	static bool led_on = false;
	static uint8_t blink_count = 0u;
	
	if(htim->Instance==TIM2)
  {
		display_number = display_number > 0u ? display_number - 1u : 0u;
		MFS_DisplayNumber(display_number);
		if(display_number == 10u)
			blink_count = 1u;
		else if(display_number == 5u)
				blink_count = 2u;
		else if(display_number == 3u)
				blink_count = 3u;
		else if(display_number == 0u)
		{
			timer_ended = true;
			timer_active = false;
		}
	}
	else if(htim->Instance==TIM3)
  {
		if(blink_count > 0u)
		{
			if(led_on)
			{
				MFS_SET_LEDS(GPIO_PIN_SET);
				HAL_GPIO_WritePin(BUZZER_GPIO_Port, BUZZER_Pin, GPIO_PIN_SET);
				led_on = false;
				blink_count--;
			}
			else
			{
				MFS_SET_LEDS(GPIO_PIN_RESET);
				HAL_GPIO_WritePin(BUZZER_GPIO_Port, BUZZER_Pin, GPIO_PIN_RESET);
				led_on = true;
			}
		}
	}
}
